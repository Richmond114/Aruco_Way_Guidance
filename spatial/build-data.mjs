// Rebuild with: node spatial/build-data.mjs (from 导盲软件).
// Source geometry and A* are retained unchanged in ./source/.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { findPath, clearSegment } from './source/navigation.js';

const directory = new URL('./', import.meta.url);
const length = (a, b) => Math.hypot(b.x - a.x, b.y - a.y);
const vector = (a, b) => ({ x: b.x - a.x, y: b.y - a.y });
const heading = v => (Math.atan2(v.x, -v.y) * 180 / Math.PI + 360) % 360;
const round = n => Math.round(n * 1e9) / 1e9;

// Image y points down, so positive cross products are clockwise/right turns.
export function routeTurn(incoming, outgoing) {
  const angleDeg = Math.atan2(incoming.x * outgoing.y - incoming.y * outgoing.x,
    incoming.x * outgoing.x + incoming.y * outgoing.y) * 180 / Math.PI;
  return { turn: Math.abs(angleDeg) < 30 ? 'straight' : angleDeg > 0 ? 'right' : 'left', angleDeg: round(angleDeg) };
}

export function buildGuideData(data, sourceHash) {
  if (!(data.scale?.metersPerPixel > 0)) throw new Error('原图缺少有效比例尺');
  const ids = new Set(data.markers.map(m => m.id));
  if (ids.size !== data.markers.length || data.tour.some(id => !ids.has(id))) throw new Error('标记 ID 或路线配置无效');
  const segments = [];
  for (let i = 1; i < data.tour.length; i++) {
    const from = data.tour[i - 1], to = data.tour[i];
    const start = data.markers.find(m => m.id === from), end = data.markers.find(m => m.id === to);
    const found = findPath(start, end, data);
    if (!found || found.length < 2) throw new Error(`路线 ${from} → ${to} 无可用图上路径`);
    const path = found.map(({ x, y }) => ({ x, y })).filter((p, j, all) => !j || length(all[j - 1], p) > 1e-8);
    for (let j = 1; j < path.length; j++) {
      if (!clearSegment(path[j - 1], path[j], data)) throw new Error(`路线 ${from} → ${to} 第 ${j} 段未通过图上通道检查`);
    }
    let lengthM = 0;
    const interiorTurns = [];
    for (let j = 1; j < path.length; j++) {
      lengthM += length(path[j - 1], path[j]) * data.scale.metersPerPixel;
      if (j < path.length - 1) {
        const change = routeTurn(vector(path[j - 1], path[j]), vector(path[j], path[j + 1]));
        if (change.turn !== 'straight') interiorTurns.push({ pathIndex: j, x: path[j].x, y: path[j].y,
          afterM: round(lengthM), ...change, registeredMarker: false });
      }
    }
    const startVector = vector(path[0], path[1]), endVector = vector(path.at(-2), path.at(-1));
    const previous = segments.at(-1);
    const change = previous ? routeTurn(vector(previous.path.at(-2), previous.path.at(-1)), startVector) : null;
    segments.push({ from, to, path, lengthM: round(lengthM), turn: change?.turn ?? null,
      signedTurnDeg: change?.angleDeg ?? null, startHeadingDeg: round(heading(startVector)),
      endHeadingDeg: round(heading(endVector)), interiorTurns, hasUnmarkedTurns: interiorTurns.length > 0,
      verified: false, distanceKind: 'drawing', turnBasis: previous ? 'previous-route-segment' : 'start-orientation-required' });
  }
  const shortOrder = [...data.experiment.shortTour];
  const routeLength = order => round(order.slice(1).reduce((sum, id, index) => {
    const segment = segments.find(s => s.from === order[index] && s.to === id);
    if (!segment) throw new Error('短线包含未生成路径');
    return sum + segment.lengthM;
  }, 0));
  return {
    schemaVersion: 1, planId: data.planId, name: data.name,
    verified: false, usage: '预设路线受控实验；位置、入口、比例尺、安装尺寸和朝向待现场核验',
    image: data.image, localImage: 'spatial/floorplan.jpg', scale: data.scale,
    markers: data.markers, routes: {
      short: { id: 'short', name: '起步短线', order: shortOrder, lengthM: routeLength(shortOrder) },
      full: { id: 'full', name: '一楼外围环线', order: [...data.tour], lengthM: routeLength(data.tour) }
    }, segments,
    source: { url: 'https://cinq929.github.io/college-1f-lab/',
      dataUrl: 'https://cinq929.github.io/college-1f-lab/architecture/floorplan.json',
      guideUrl: 'https://cinq929.github.io/college-1f-lab/guide.html',
      accessedOn: '2026-11-14', floorplanSha256: sourceHash,
      algorithm: '原空间导览 A*，按图上通行区检查并进行视线简化',
      coordinateSystem: '图像 x 向右、y 向下；航向 0° 朝图上、90° 朝图右' },
    notes: [...data.notes,
      '转向依据按路线顺序进入站点时的预设方向；扫描本身不证明身体朝向或到达码中心。',
      '内部转折未自动注册为新标记；不可只连接站点中心后据此进行现场转向。',
      '图上长度是图纸估算，不是实时剩余距离或可独立通行保证。',
      '原空间导览的 P 补码候选没有登记 ID，未加入扫码列表。']
  };
}

export async function generate() {
  const bytes = await readFile(new URL('floorplan.json', directory));
  const data = JSON.parse(bytes.toString('utf8'));
  const hash = createHash('sha256').update(bytes).digest('hex');
  const plan = buildGuideData(data, hash);
  const output = `// Generated by spatial/build-data.mjs. Do not mix this plan with legacy marker IDs.\n(function(root, factory) {\n  if (typeof module === 'object' && module.exports) module.exports = factory();\n  else root.GUIDE_PLAN = factory();\n})(typeof globalThis !== 'undefined' ? globalThis : this, function() {\n  return ${JSON.stringify(plan, null, 2)};\n});\n`;
  await writeFile(new URL('guide-data.js', directory), output, 'utf8');
  return plan;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const plan = await generate();
  console.log(`${plan.markers.length} markers; ${plan.segments.length} segments; drawing length ${plan.routes.full.lengthM.toFixed(1)} m`);
  for (const segment of plan.segments.filter(s => s.hasUnmarkedTurns)) {
    console.log(`${segment.from} → ${segment.to}: ${segment.interiorTurns.length} unmarked interior turn(s)`);
  }
}
